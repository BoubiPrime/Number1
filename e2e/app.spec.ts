test('gestion complète : cinq tours, recalcul, édition, suppression et persistance', async ({page}) => {
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.evaluate(()=>localStorage.setItem('racelab.sessions.v1','[]'));
  await page.reload();
  await page.getByRole('button',{name:'Nouvelle session',exact:true}).click();
  await page.getByLabel('Circuit',{exact:true}).fill('Silverstone');
  await page.getByLabel('Voiture',{exact:true}).fill('Aston Martin Vantage GT3');
  await page.getByLabel('Jeu',{exact:true}).fill('Project Motor Racing');
  await page.getByLabel('Date',{exact:true}).fill('2026-10-18');
  await page.getByLabel('Type de session',{exact:true}).selectOption('Essais');
  await page.getByRole('button',{name:'Créer la session',exact:true}).click();
  const originalId = await page.evaluate(()=>JSON.parse(localStorage.getItem('racelab.sessions.v1')!)[0].id);
  expect(originalId).toBeTruthy();
  for(const time of ['1:40.000','102.000','1:38.000','104.000','1:46.000']) {
    await page.getByLabel('Chrono',{exact:true}).fill(time);
    await page.getByRole('button',{name:'Ajouter le tour'}).click();
  }
  const rows=page.locator('.laps-panel tbody tr');
  await expect(rows).toHaveCount(5);
  await expect(page.locator('.pace-hero>strong')).toHaveText('1:38.000');
  await expect(page.locator('.pace-row').nth(0)).toContainText('1:42.000');
  await expect(page.locator('.pace-row').nth(1)).toContainText('8.000 s');
  await expect(page.locator('.metric').nth(3)).toContainText('2.828 s');
  const lapIds=await page.evaluate(()=>JSON.parse(localStorage.getItem('racelab.sessions.v1')!)[0].laps.map((l:{id:string})=>l.id));
  await page.getByRole('button',{name:'Invalider le tour 3',exact:true}).click();
  await expect(page.locator('.pace-hero>strong')).toHaveText('1:40.000');
  await expect(page.locator('.pace-row').nth(0)).toContainText('1:43.000');
  await expect(page.locator('.pace-row').nth(1)).toContainText('6.000 s');
  await expect(page.locator('.pace-row').nth(2)).toContainText('4 / 5');
  await expect(page.locator('.metric').nth(3)).toContainText('2.236 s');
  await expect(rows.nth(1).locator('td').nth(2)).toHaveText('+2.000');
  await page.getByRole('button',{name:'Modifier le tour 2',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await expect(dialog.getByLabel('Chrono',{exact:true})).toHaveValue('1:42.000');
  await dialog.getByLabel('Chrono',{exact:true}).fill('1:99.000');
  await dialog.getByRole('button',{name:'Enregistrer le chrono'}).click();
  await expect(dialog.getByRole('alert')).toContainText('Format attendu');
  await dialog.getByLabel('Chrono',{exact:true}).fill('99.000');
  await dialog.getByRole('button',{name:'Enregistrer le chrono'}).click();
  await expect(page.locator('.pace-hero>strong')).toHaveText('1:39.000');
  await expect(rows.nth(1).locator('td').nth(1)).toContainText('1:39.000');
  await page.getByRole('button',{name:'Modifier le tour 2',exact:true}).click();
  await dialog.getByLabel('Chrono',{exact:true}).fill('88.000');
  await dialog.getByRole('button',{name:'Annuler',exact:true}).click();
  await expect(page.locator('.pace-hero>strong')).toHaveText('1:39.000');
  await page.getByRole('button',{name:'Supprimer le tour 4',exact:true}).click();
  await expect(rows).toHaveCount(4);
  await expect(rows.locator('td:first-child')).toHaveText(['01','02','03','04']);
  await page.getByRole('button',{name:'Modifier la session',exact:true}).click();
  await expect(dialog.getByLabel('Circuit',{exact:true})).toHaveValue('Silverstone');
  await dialog.getByLabel('Circuit',{exact:true}).fill('Silverstone GP');
  await dialog.getByLabel('Voiture',{exact:true}).fill('Ferrari 296 GT3');
  await dialog.getByLabel('Jeu',{exact:true}).fill('F1 24');
  await dialog.getByLabel('Date',{exact:true}).fill('2026-10-17');
  await dialog.getByLabel('Type de session',{exact:true}).selectOption('Qualifications');
  await dialog.getByRole('button',{name:'Enregistrer les modifications'}).click();
  await expect(page.getByRole('heading',{level:1})).toHaveText('Silverstone GP');
  await page.reload();
  await page.getByRole('button',{name:'Silverstone GP F1 24',exact:true}).click();
  await expect(rows).toHaveCount(4);
  await expect(page.locator('.pace-hero>strong')).toHaveText('1:39.000');
  const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('racelab.sessions.v1')!)[0]);
  expect(stored).toMatchObject({id:originalId,circuit:'Silverstone GP',car:'Ferrari 296 GT3',game:'F1 24',date:'2026-10-17',type:'Qualifications'});
  expect(stored.laps.map((l:{id:string})=>l.id)).toEqual([lapIds[0],lapIds[1],lapIds[2],lapIds[4]]);
  expect(stored.laps[1].timeMs).toBe(99000);
  expect(stored.laps[2].valid).toBe(false);
  for(const n of [1,2,4]) await page.getByRole('button',{name:`Invalider le tour ${n}`,exact:true}).click();
  await expect(page.locator('.pace-hero>strong')).toHaveText('—');
  await expect(page.locator('.pace-row').nth(0)).toContainText('—');
  await expect(page.locator('.metric').nth(3)).toContainText('—');
  await page.getByRole('button',{name:'Supprimer cette session',exact:true}).click();
  await dialog.getByRole('button',{name:'Confirmer la suppression'}).click();
  await expect(page.getByRole('status')).toContainText('Session supprimée');
  await page.reload();
  expect(await page.evaluate(()=>localStorage.getItem('racelab.sessions.v1'))).toBe('[]');
  expect(errors).toEqual([]);
});
